    j = ndimage.distance_transform_edt(hole, return_distances=False, return_indices=True)
    out = img[j[0], j[1]]
    if blur:
        out = np.stack([ndimage.gaussian_filter(out[..., k], blur) for k in range(3)], axis=2)
    return np.where(hole[..., None], out, img)

